"""Local projection derivatives for existing finite human primitive stations.

This is a derivative carrier only. The original dynamic human query remains
the source value and trial guard. A foot is interpolated on the *projected*
nominal segment, never generated by projecting an interpolated world point.
"""
from __future__ import annotations

import operator
import numpy as np


def _helpers():
    from structured_programme_source_candidate.native_camera_local import native_camera_local
    from structured_programme_source_candidate.fixed_pivot_positive_domain_fd import positive_pivot_coordinate_derivative
    from structured_programme_source_candidate.human_constraint_dependency_fd import group_dependencies
    from wide_anchor_candidate.full_brown_projection import project_central_valid_full_brown
    return native_camera_local, positive_pivot_coordinate_derivative, group_dependencies, project_central_valid_full_brown


def _state(truth, value):
    value = np.asarray(value, float)
    if value.shape != (truth.parameter_count,):
        raise ValueError('Complete shared source q required for finite station projection')
    if not np.isfinite(value).all() or np.any(value[truth.height_columns] <= 0.):
        raise ValueError('Finite station projection retains strictly positive physical pivots')
    truth.state.geometry.validate_parameters(value[truth.world_indices])
    return value


def _contexts(truth, contexts):
    records = truth.full_stroke_records
    if records is None:
        raise ValueError('Original complete human stroke records required')
    result = []
    for context in contexts:
        group = operator.index(context['group'])
        vertex = operator.index(context['source_vertex'])
        segment = operator.index(context['segment'])
        station = float(context['station'])
        if (group < 0 or group >= len(records) or context['record'] is not records[group]
                or vertex < 0 or vertex >= len(records[group]['uv'])
                or segment < 0 or not np.isfinite(station) or not 0. <= station <= 1.):
            raise ValueError('Authenticated full-stroke group/vertex and nominal segment station required')
        result.append(dict(context, group=group, source_vertex=vertex,
                           segment=segment, station=station))
    return result


def _project(truth, value, contexts, helpers, endpoint_masks=None):
    value = _state(truth, value)
    native_camera_local, _, _, project = helpers
    core = value[:truth.state.structured_programme_coordinate_chart.core_count]
    cameras, curves, rows = {}, {}, []
    for ordinal, context in enumerate(contexts):
        record = context['record']
        actual = int(record['row']['actual_pts'])
        if actual not in cameras:
            block = truth.blocks[actual]
            cameras[actual] = block.bundle.camera(native_camera_local(block, core), actual)
        # Contexts on a complete physical line share one current producer
        # certificate for this exact FD sample. Authenticate it alongside the
        # existing per-record curve construction, not once per stroke vertex.
        whole_vertical=bool(context.get('whole_vertical_print',False))
        whole_boundary=bool(context.get('whole_boundary_clipped_straight',False))
        if whole_vertical and whole_boundary:
            raise ValueError('One exact original whole physical primitive certificate required')
        whole=whole_vertical or whole_boundary
        key = (id(record),whole_vertical,whole_boundary)
        if key not in curves:
            if whole_vertical:
                from .finite_rectangle_station_step_constraints import _current_vertical_print_primitive
                world=_current_vertical_print_primitive(record,value)
                if world is None:
                    raise ValueError('Interior sample requires the current whole vertical physical print certificate')
            elif whole_boundary:
                from .finite_rectangle_station_step_constraints import _current_boundary_clipped_primitive
                world=_current_boundary_clipped_primitive(record,value)
                if world is None:
                    raise ValueError('Interior sample requires the current whole boundary-clipped straight physical line certificate')
            else:world = np.asarray(record['factor']._world(value, record['row']['curve']), float)
            if world.ndim != 2 or world.shape[1] != 3 or len(world) < 2 or not np.isfinite(world).all():
                raise ValueError('Original finite world primitive required')
            pixel, depth, central = project(cameras[actual], world)
            midpoint = project(cameras[actual], .5 * (world[:-1] + world[1:]))[-1]
            curves[key] = (pixel, depth, central, midpoint, len(world))
        pixel, depth, central, midpoint, count = curves[key]
        segment = context['segment']
        if not whole and segment not in (0, count - 2):
            raise ValueError('Nominal first or last finite physical segment required')
        indices = np.array([segment, segment + 1])
        if (not np.all(central[indices]) or not np.all(depth[indices] > 0.)
                or not np.isfinite(pixel[indices]).all() or not midpoint[segment]):
            raise ValueError('Near physical endpoint and nominal segment must retain positive central support')
        delta = pixel[segment + 1] - pixel[segment]
        if float(delta @ delta) <= 1e-4:
            raise ValueError('Original finite projected segment is degenerate')
        valid_ends = central[[0, -1]] & (depth[[0, -1]] > 0.) & np.isfinite(pixel[[0, -1]]).all(axis=1)
        required_mask=(endpoint_masks[ordinal]if endpoint_masks is not None else
            context.get('required_physical_endpoint_valid'))
        if required_mask is not None:
            required = np.asarray(required_mask, bool)
            if required.shape!=(2,):raise ValueError('Exact nominal physical endpoint validity required')
            if not np.all(valid_ends[required]):
                raise ValueError('Nominally used physical endpoint left positive central support')
            valid_ends = required
        endpoints = np.zeros((2, 2))
        endpoints[valid_ends] = pixel[[0, -1]][valid_ends]
        rows.append(dict(foot=pixel[segment] + context['station'] * delta,
                         endpoints=endpoints, endpoint_valid=valid_ends.copy(), tangent=delta * (count - 1),
                         station=(segment + context['station']) / (count - 1),
                         proof=dict(actual_pts=actual, world_vertex_count=count,
                                    projected_segment=segment,
                                    endpoint_depth=depth[[0, -1]].tolist(),
                                    nominal_segment_depth=depth[segment:segment + 2].tolist(),
                                    near_endpoint_and_segment_positive_central=True,
                                    endpoint_valid=valid_ends.tolist(),
                                    invalid_far_endpoint_zero_placeholder_not_used=True,
                                    projected_segment_midpoint_positive_central=True)))
    return rows


def projected_physical_endpoint_carriers(truth, value, contexts):
    """Return actual physical endpoint XY, in context order, without a J."""
    contexts = _contexts(truth, contexts)
    rows = _project(truth, value, contexts, _helpers())
    return np.asarray([row['endpoints'] for row in rows], float).reshape(-1, 2, 2)


def projected_fixed_foot_carriers(truth,value,contexts):
    """The same original projected segment/t foot used by the local J.

    This is a fixed local witness, not the dynamically rebalanced guard. A
    sampling knot remains an interior physical station. The original guard
    independently decides whether another witness makes the trial feasible.
    """
    contexts=_contexts(truth,contexts)
    rows=_project(truth,value,contexts,_helpers())
    return np.asarray([row['foot']for row in rows],float).reshape(-1,2)


def projected_station_contexts(truth, q, contexts, selected):
    """Differentiate only selected columns in each original group dependency.

The original coordinate steps and positive-pivot stencil are reused. Complete
state/world validation is applied to each real sample; only the corresponding
exposure cameras and original primitives are constructed for that sample.
"""
    q = _state(truth, q)
    contexts = _contexts(truth, contexts)
    raw_selected = np.asarray(selected)
    if raw_selected.ndim != 1 or raw_selected.dtype.kind not in 'iu':
        raise ValueError('Explicit integral selected source columns required')
    selected = np.asarray(raw_selected, int)
    if (len(np.unique(selected)) != len(selected) or np.any(selected < 0)
            or np.any(selected >= truth.parameter_count)):
        raise ValueError('Distinct selected columns in complete q required')
    helpers = _helpers()
    derivative, dependencies = helpers[1], helpers[2](truth, truth.full_stroke_records)
    nominal = _project(truth, q, contexts, helpers)
    count, width = len(contexts), len(selected)
    foot_j = np.zeros((count, 2, width))
    endpoint_j = np.zeros((count, 2, 2, width))
    dependency_sets = [set(map(int, dependencies[c['group']])) for c in contexts]
    real_columns, evaluations = [], 0
    try:
        for position, column in enumerate(selected):
            involved = [i for i, deps in enumerate(dependency_sets) if int(column) in deps]
            if not involved:
                continue
            subset = [contexts[i] for i in involved]
            base = np.asarray([np.r_[nominal[i]['foot'], nominal[i]['endpoints'].ravel()]
                               for i in involved]).ravel()

            def evaluate(value):
                nonlocal evaluations
                evaluations += 1
                rows = _project(truth, value, subset, helpers,
                                endpoint_masks=[nominal[i]['endpoint_valid'] for i in involved])
                return np.asarray([np.r_[r['foot'], r['endpoints'].ravel()] for r in rows]).ravel()

            d = derivative(evaluate, q, int(column), truth.steps.get(int(column), 1e-6),
                           truth.height_columns, base=base).reshape(-1, 6)
            foot_j[involved, :, position] = d[:, :2]
            endpoint_j[involved, :, :, position] = d[:, 2:].reshape(-1, 2, 2)
            real_columns.append(int(column))
    finally:
        # Restore only owned exposure bindings; no full query/J is constructed.
        _project(truth, q, contexts, helpers)
    return dict(projected_foot_xy=np.asarray([r['foot'] for r in nominal]).reshape(count, 2),
                fixed_foot_jacobian=foot_j,
                station_screen_tangent=np.asarray([r['tangent'] for r in nominal]).reshape(count, 2),
                nominal_physical_station=np.asarray([r['station'] for r in nominal]),
                physical_endpoints_xy=np.asarray([r['endpoints'] for r in nominal]).reshape(count, 2, 2),
                endpoint_valid=np.asarray([r['endpoint_valid'] for r in nominal], bool).reshape(count, 2),
                endpoint_jacobian=endpoint_j,
                report=dict(schema='rinkspace.finite-rectangle-projected-station-FD.v1',
                            selected_columns=selected.tolist(), actual_FD_columns=real_columns,
                            real_FD_evaluations=evaluations,
                            dependent_selected_columns=[[int(c) for c in selected if int(c) in deps]
                                                        for deps in dependency_sets],
                            projection_validation=[r['proof'] for r in nominal],
                            complete_q_world_and_positive_pivot_validation_per_sample=True,
                            original_coordinate_steps_and_positive_pivot_FD_retained=True,
                            source_UV_normals_world_role_and_dynamic_guard_unchanged=True,
                            projected_segment_interpolation_not_world_point_projection=True))
